#!/usr/bin/env python3
"""Build Pixel Icons from Azganoth/pixel-icons at 8ca335513134e8417c06a00f689b492d5a79bb70.

Usage: python generate.py /path/to/pixel-icons-repo [output-directory]
Requires fontTools and Pillow. Outputs are deterministic for identical inputs and
library versions; the distributed files use fontTools 4.63.0 and Pillow 13.0.0.
"""

import json
import sys
from pathlib import Path

from fontTools.colorLib.builder import buildCOLR, buildCPAL
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from PIL import Image

SOURCE = Path(sys.argv[1]) / "assets"
OUTPUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent
THEME = json.loads((SOURCE / "theme.json").read_text(encoding="utf-8"))
SCALE = 64
# Nerd Fonts 3.5.0 uses U+F0001..U+F1AF0 for Material Design icons.
FIRST_CODEPOINT = 0xF2000


def glyph(pixels):
    pen = TTGlyphPen(None)
    for x, y in pixels:
        left, top = x * SCALE, 896 - y * SCALE
        pen.moveTo((left, top))
        pen.lineTo((left + SCALE, top))
        pen.lineTo((left + SCALE, top - SCALE))
        pen.lineTo((left, top - SCALE))
        pen.closePath()
    return pen.glyph()


def lua_string(value):
    return json.dumps(value, ensure_ascii=False)


def build():
    definitions = THEME["iconDefinitions"] | {
        "nix_file": {"iconPath": str(Path(__file__).with_name("nix.png"))},
        "zz_lock_file": {"iconPath": str(Path(__file__).with_name("lock.png"))},
    }
    names = sorted(definitions)
    images = {}
    colors = set()
    for name in names:
        with Image.open(SOURCE / definitions[name]["iconPath"]) as image:
            image = image.convert("RGBA").resize((8, 8), Image.Resampling.NEAREST)
            image = image.resize((16, 16), Image.Resampling.NEAREST)
            pixels = list(image.get_flattened_data())
            images[name] = (image.width, image.height, pixels)
            colors.update(color for color in pixels if color[3])

    palette = sorted(colors)
    indices = {color: index for index, color in enumerate(palette)}
    glyphs = {".notdef": glyph([])}
    layers = {}
    cmap = {}
    for index, name in enumerate(names):
        base = f"icon{index:03d}"
        cmap[FIRST_CODEPOINT + index] = base
        width, height, pixels = images[name]
        by_color = {}
        for y in range(height):
            for x in range(width):
                color = pixels[y * width + x]
                if color[3]:
                    by_color.setdefault(color, []).append((x, y))
        glyphs[base] = glyph([pixel for color in sorted(by_color) for pixel in by_color[color]])
        layers[base] = []
        for layer, color in enumerate(sorted(by_color)):
            layer_name = f"{base}.layer{layer:03d}"
            glyphs[layer_name] = glyph(by_color[color])
            layers[base].append((layer_name, indices[color]))

    font = FontBuilder(1024, isTTF=True)
    font.setupGlyphOrder(list(glyphs))
    font.setupCharacterMap(cmap)
    font.setupGlyf(glyphs)
    # CoreText positions each color layer using its left-side bearing.
    font.setupHorizontalMetrics({
        name: (1024, glyph.xMin if glyph.numberOfContours else 0)
        for name, glyph in glyphs.items()
    })
    font.setupHorizontalHeader(ascent=896, descent=-128)
    font.setupNameTable({"familyName": "Pixel Icons", "styleName": "Regular", "uniqueFontIdentifier": "Pixel Icons Regular 1.0", "fullName": "Pixel Icons Regular", "psName": "PixelIcons-Regular", "version": "Version 1.0", "copyright": "Pixel Icons copyright 2025 Azganoth; NixOS glyph from Font Logos.", "licenseDescription": "Pixel Icons: MIT; NixOS glyph: Unlicense. See accompanying license files."})
    font.setupOS2(sTypoAscender=896, sTypoDescender=-128, usWinAscent=896, usWinDescent=128)
    font.setupPost()
    font.setupMaxp()
    font.font["COLR"] = buildCOLR(layers, version=0, glyphMap=font.font.getReverseGlyphMap())
    font.font["CPAL"] = buildCPAL([[tuple(channel / 255 for channel in color) for color in palette]])
    font.font["head"].created = font.font["head"].modified = 2082844800
    font.font.recalcTimestamp = False
    OUTPUT.mkdir(parents=True, exist_ok=True)
    font.save(OUTPUT / "PixelIcons.ttf")

    lines = ["-- Generated by generate.py; do not edit.", "local icons = {"]
    for index, name in enumerate(names):
        lines.append(f"  [{lua_string(name)}] = {lua_string(chr(FIRST_CODEPOINT + index))},")
    lines.extend(["}", "", "return {", "  iconDefinitions = icons,"])
    for key in ("fileExtensions", "fileNames", "folderNames", "folderNamesExpanded"):
        lines.append(f"  {key} = {{")
        mappings = THEME[key] | ({"nix": "nix_file", "lock": "zz_lock_file"} if key == "fileExtensions" else {})
        for name, definition in sorted(mappings.items()):
            lines.append(f"    [{lua_string(name)}] = icons[{lua_string(definition)}],")
        lines.append("  },")
    for key in ("file", "folder", "folderExpanded"):
        lines.append(f"  {key} = icons[{lua_string(THEME[key])}],")
    lines.extend(["}", ""])
    (OUTPUT / "icons.lua").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    build()
